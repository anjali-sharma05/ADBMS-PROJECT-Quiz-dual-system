PROMPT ------------------------------------------------------------------------
PROMPT 5. CREATING PL/SQL PACKAGE BODY (PKG_QUIZ_MANAGER)
PROMPT ------------------------------------------------------------------------

CREATE OR REPLACE PACKAGE BODY PKG_QUIZ_MANAGER AS

    -- 1. FN_CALCULATE_PERCENTAGE
    FUNCTION FN_CALCULATE_PERCENTAGE(
        p_score IN NUMBER,
        p_total IN NUMBER
    ) RETURN NUMBER IS
    BEGIN
        IF p_total IS NULL OR p_total <= 0 THEN
            RETURN 0;
        END IF;
        RETURN ROUND((p_score / p_total) * 100, 2);
    EXCEPTION
        WHEN OTHERS THEN
            RETURN 0;
    END FN_CALCULATE_PERCENTAGE;

    -- 2. FN_GET_PERFORMANCE_MSG
    FUNCTION FN_GET_PERFORMANCE_MSG(
        p_percentage IN NUMBER
    ) RETURN VARCHAR2 IS
    BEGIN
        IF p_percentage >= 80 THEN
            RETURN 'Excellent Performance!';
        ELSIF p_percentage >= 60 THEN
            RETURN 'Good Performance!';
        ELSIF p_percentage >= 40 THEN
            RETURN 'Average Performance!';
        ELSE
            RETURN 'Keep Practicing!';
        END IF;
    END FN_GET_PERFORMANCE_MSG;

    -- 3. FN_CHECK_ANSWER
    FUNCTION FN_CHECK_ANSWER(
        p_question_id     IN NUMBER,
        p_selected_option IN VARCHAR2
    ) RETURN NUMBER IS
        v_correct VARCHAR2(500);
    BEGIN
        SELECT CORRECT_ANSWER
          INTO v_correct
          FROM QUIZ_QUESTIONS
         WHERE QUESTION_ID = p_question_id;

        IF TRIM(p_selected_option) = TRIM(v_correct) THEN
            RETURN 1;
        ELSE
            RETURN 0;
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 0;
        WHEN OTHERS THEN
            RETURN 0;
    END FN_CHECK_ANSWER;

    -- 4. FN_COUNT_QUESTIONS
    FUNCTION FN_COUNT_QUESTIONS(
        p_subject_name IN VARCHAR2 DEFAULT NULL
    ) RETURN NUMBER IS
        v_count NUMBER := 0;
    BEGIN
        IF p_subject_name IS NULL THEN
            SELECT COUNT(*) INTO v_count FROM QUIZ_QUESTIONS;
        ELSE
            SELECT COUNT(q.QUESTION_ID)
              INTO v_count
              FROM QUIZ_QUESTIONS q
              JOIN QUIZ_SUBJECTS s ON q.SUBJECT_ID = s.SUBJECT_ID
             WHERE UPPER(s.SUBJECT_NAME) = UPPER(TRIM(p_subject_name));
        END IF;
        RETURN v_count;
    END FN_COUNT_QUESTIONS;

    -- 5. FN_COUNT_ATTEMPTS
    FUNCTION FN_COUNT_ATTEMPTS(
        p_subject_name IN VARCHAR2 DEFAULT NULL
    ) RETURN NUMBER IS
        v_count NUMBER := 0;
    BEGIN
        IF p_subject_name IS NULL THEN
            SELECT COUNT(*) INTO v_count FROM QUIZ_ATTEMPTS;
        ELSE
            SELECT COUNT(a.ATTEMPT_ID)
              INTO v_count
              FROM QUIZ_ATTEMPTS a
              JOIN QUIZ_SUBJECTS s ON a.SUBJECT_ID = s.SUBJECT_ID
             WHERE UPPER(s.SUBJECT_NAME) = UPPER(TRIM(p_subject_name));
        END IF;
        RETURN v_count;
    END FN_COUNT_ATTEMPTS;

    -- 6. FN_GET_HIGHEST_SCORE
    FUNCTION FN_GET_HIGHEST_SCORE(
        p_subject_name IN VARCHAR2
    ) RETURN NUMBER IS
        v_max NUMBER := 0;
    BEGIN
        SELECT NVL(MAX(a.SCORE), 0)
          INTO v_max
          FROM QUIZ_ATTEMPTS a
          JOIN QUIZ_SUBJECTS s ON a.SUBJECT_ID = s.SUBJECT_ID
         WHERE UPPER(s.SUBJECT_NAME) = UPPER(TRIM(p_subject_name));
        RETURN v_max;
    EXCEPTION
        WHEN OTHERS THEN
            RETURN 0;
    END FN_GET_HIGHEST_SCORE;

    -- 7. SP_GET_SUBJECTS
    PROCEDURE SP_GET_SUBJECTS(
        p_cursor OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT s.SUBJECT_ID,
                   s.SUBJECT_NAME,
                   s.DESCRIPTION,
                   COUNT(q.QUESTION_ID) AS QUESTION_COUNT
              FROM QUIZ_SUBJECTS s
              LEFT JOIN QUIZ_QUESTIONS q ON s.SUBJECT_ID = q.SUBJECT_ID
             GROUP BY s.SUBJECT_ID, s.SUBJECT_NAME, s.DESCRIPTION
             ORDER BY s.SUBJECT_NAME ASC;
    END SP_GET_SUBJECTS;

    -- 8. SP_GET_QUESTIONS_BY_SUBJECT
    PROCEDURE SP_GET_QUESTIONS_BY_SUBJECT(
        p_subject_name IN VARCHAR2,
        p_limit        IN NUMBER DEFAULT 5,
        p_cursor       OUT SYS_REFCURSOR
    ) IS
        v_limit NUMBER := NVL(p_limit, 5);
    BEGIN
        OPEN p_cursor FOR
            SELECT q.QUESTION_ID,
                   q.QUESTION_TEXT,
                   q.OPTION_A,
                   q.OPTION_B,
                   q.OPTION_C,
                   q.OPTION_D,
                   q.CORRECT_ANSWER
              FROM QUIZ_QUESTIONS q
              JOIN QUIZ_SUBJECTS s ON q.SUBJECT_ID = s.SUBJECT_ID
             WHERE UPPER(s.SUBJECT_NAME) = UPPER(TRIM(p_subject_name))
             ORDER BY DBMS_RANDOM.VALUE
             FETCH FIRST v_limit ROWS ONLY;
    END SP_GET_QUESTIONS_BY_SUBJECT;

    -- 9. SP_SAVE_QUIZ_ATTEMPT
    PROCEDURE SP_SAVE_QUIZ_ATTEMPT(
        p_username        IN VARCHAR2,
        p_subject_name    IN VARCHAR2,
        p_score           IN NUMBER,
        p_total_questions IN NUMBER,
        p_attempt_id      OUT NUMBER,
        p_percentage      OUT NUMBER,
        p_perf_msg        OUT VARCHAR2
    ) IS
        v_user_id    NUMBER;
        v_subject_id NUMBER;
        v_user       VARCHAR2(100) := NVL(TRIM(p_username), 'Student');
    BEGIN
        -- Find or create user
        BEGIN
            SELECT USER_ID INTO v_user_id
              FROM QUIZ_USERS
             WHERE UPPER(USERNAME) = UPPER(v_user);
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                INSERT INTO QUIZ_USERS (USERNAME, FULL_NAME)
                VALUES (v_user, v_user)
                RETURNING USER_ID INTO v_user_id;
        END;

        -- Find subject
        SELECT SUBJECT_ID INTO v_subject_id
          FROM QUIZ_SUBJECTS
         WHERE UPPER(SUBJECT_NAME) = UPPER(TRIM(p_subject_name));

        -- Calculate percentage and performance message via PL/SQL functions
        p_percentage := FN_CALCULATE_PERCENTAGE(p_score, p_total_questions);
        p_perf_msg   := FN_GET_PERFORMANCE_MSG(p_percentage);

        -- Insert attempt record
        INSERT INTO QUIZ_ATTEMPTS (
            USER_ID,
            SUBJECT_ID,
            SCORE,
            TOTAL_QUESTIONS,
            PERCENTAGE,
            PERFORMANCE_MESSAGE,
            ATTEMPT_DATE
        ) VALUES (
            v_user_id,
            v_subject_id,
            p_score,
            p_total_questions,
            p_percentage,
            p_perf_msg,
            CURRENT_TIMESTAMP
        ) RETURNING ATTEMPT_ID INTO p_attempt_id;

        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20002, 'Subject "' || p_subject_name || '" not found.');
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END SP_SAVE_QUIZ_ATTEMPT;

    -- 10. SP_RECORD_QUIZ_RESPONSE
    PROCEDURE SP_RECORD_QUIZ_RESPONSE(
        p_attempt_id      IN NUMBER,
        p_question_id     IN NUMBER,
        p_selected_option IN VARCHAR2,
        p_is_correct      OUT NUMBER
    ) IS
        v_correct_opt VARCHAR2(500);
    BEGIN
        -- Lookup correct answer
        SELECT CORRECT_ANSWER
          INTO v_correct_opt
          FROM QUIZ_QUESTIONS
         WHERE QUESTION_ID = p_question_id;

        IF TRIM(p_selected_option) = TRIM(v_correct_opt) THEN
            p_is_correct := 1;
        ELSE
            p_is_correct := 0;
        END IF;

        -- Insert individual response record
        INSERT INTO QUIZ_RESPONSES (
            ATTEMPT_ID,
            QUESTION_ID,
            SELECTED_OPTION,
            CORRECT_OPTION,
            IS_CORRECT,
            ANSWERED_AT
        ) VALUES (
            p_attempt_id,
            p_question_id,
            p_selected_option,
            v_correct_opt,
            p_is_correct,
            CURRENT_TIMESTAMP
        );

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END SP_RECORD_QUIZ_RESPONSE;

    -- 11. SP_GET_USER_HISTORY
    PROCEDURE SP_GET_USER_HISTORY(
        p_username IN VARCHAR2 DEFAULT NULL,
        p_limit    IN NUMBER DEFAULT 20,
        p_cursor   OUT SYS_REFCURSOR
    ) IS
        v_limit NUMBER := NVL(p_limit, 20);
    BEGIN
        OPEN p_cursor FOR
            SELECT a.ATTEMPT_ID,
                   u.USERNAME,
                   s.SUBJECT_NAME,
                   a.SCORE,
                   a.TOTAL_QUESTIONS,
                   a.PERCENTAGE,
                   a.PERFORMANCE_MESSAGE,
                   TO_CHAR(a.ATTEMPT_DATE, 'YYYY-MM-DD HH24:MI:SS') AS ATTEMPT_TIME
              FROM QUIZ_ATTEMPTS a
              JOIN QUIZ_SUBJECTS s ON a.SUBJECT_ID = s.SUBJECT_ID
              LEFT JOIN QUIZ_USERS u ON a.USER_ID = u.USER_ID
             WHERE (p_username IS NULL OR UPPER(u.USERNAME) = UPPER(TRIM(p_username)))
             ORDER BY a.ATTEMPT_DATE DESC
             FETCH FIRST v_limit ROWS ONLY;
    END SP_GET_USER_HISTORY;

    -- 12. SP_GET_SUBJECT_PERFORMANCE
    PROCEDURE SP_GET_SUBJECT_PERFORMANCE(
        p_cursor OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT s.SUBJECT_NAME,
                   COUNT(a.ATTEMPT_ID) AS TOTAL_ATTEMPTS,
                   NVL(ROUND(AVG(a.PERCENTAGE), 1), 0) AS AVG_PERCENTAGE,
                   NVL(MAX(a.SCORE), 0) AS HIGHEST_SCORE,
                   COUNT(DISTINCT q.QUESTION_ID) AS TOTAL_QUESTIONS
              FROM QUIZ_SUBJECTS s
              LEFT JOIN QUIZ_ATTEMPTS a ON s.SUBJECT_ID = a.SUBJECT_ID
              LEFT JOIN QUIZ_QUESTIONS q ON s.SUBJECT_ID = q.SUBJECT_ID
             GROUP BY s.SUBJECT_NAME
             ORDER BY s.SUBJECT_NAME ASC;
    END SP_GET_SUBJECT_PERFORMANCE;

    -- 13. SP_ADD_QUESTION
    PROCEDURE SP_ADD_QUESTION(
        p_subject_name IN VARCHAR2,
        p_question_text IN VARCHAR2,
        p_opt_a        IN VARCHAR2,
        p_opt_b        IN VARCHAR2,
        p_opt_c        IN VARCHAR2,
        p_opt_d        IN VARCHAR2,
        p_correct_ans  IN VARCHAR2,
        p_question_id  OUT NUMBER
    ) IS
        v_subject_id NUMBER;
    BEGIN
        SELECT SUBJECT_ID INTO v_subject_id
          FROM QUIZ_SUBJECTS
         WHERE UPPER(SUBJECT_NAME) = UPPER(TRIM(p_subject_name));

        INSERT INTO QUIZ_QUESTIONS (
            SUBJECT_ID,
            QUESTION_TEXT,
            OPTION_A,
            OPTION_B,
            OPTION_C,
            OPTION_D,
            CORRECT_ANSWER
        ) VALUES (
            v_subject_id,
            TRIM(p_question_text),
            TRIM(p_opt_a),
            TRIM(p_opt_b),
            TRIM(p_opt_c),
            TRIM(p_opt_d),
            TRIM(p_correct_ans)
        ) RETURNING QUESTION_ID INTO p_question_id;

        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20003, 'Subject "' || p_subject_name || '" does not exist.');
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END SP_ADD_QUESTION;

    -- 14. SP_UPDATE_QUESTION
    PROCEDURE SP_UPDATE_QUESTION(
        p_question_id  IN NUMBER,
        p_question_text IN VARCHAR2,
        p_opt_a        IN VARCHAR2,
        p_opt_b        IN VARCHAR2,
        p_opt_c        IN VARCHAR2,
        p_opt_d        IN VARCHAR2,
        p_correct_ans  IN VARCHAR2
    ) IS
    BEGIN
        UPDATE QUIZ_QUESTIONS
           SET QUESTION_TEXT  = TRIM(p_question_text),
               OPTION_A       = TRIM(p_opt_a),
               OPTION_B       = TRIM(p_opt_b),
               OPTION_C       = TRIM(p_opt_c),
               OPTION_D       = TRIM(p_opt_d),
               CORRECT_ANSWER = TRIM(p_correct_ans)
         WHERE QUESTION_ID    = p_question_id;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'Question ID ' || p_question_id || ' not found.');
        END IF;

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END SP_UPDATE_QUESTION;

    -- 15. SP_DELETE_QUESTION
    PROCEDURE SP_DELETE_QUESTION(
        p_question_id IN NUMBER
    ) IS
    BEGIN
        DELETE FROM QUIZ_QUESTIONS
         WHERE QUESTION_ID = p_question_id;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Question ID ' || p_question_id || ' not found.');
        END IF;

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END SP_DELETE_QUESTION;

END PKG_QUIZ_MANAGER;
/

