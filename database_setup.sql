PROMPT ------------------------------------------------------------------------
PROMPT 2. CREATING SCHEMA TABLES
PROMPT ------------------------------------------------------------------------

-- 1. QUIZ_SUBJECTS
CREATE TABLE QUIZ_SUBJECTS (
    SUBJECT_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SUBJECT_NAME VARCHAR2(100) NOT NULL CONSTRAINT UQ_SUBJECT_NAME UNIQUE,
    DESCRIPTION  VARCHAR2(255),
    CREATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. QUIZ_QUESTIONS
CREATE TABLE QUIZ_QUESTIONS (
    QUESTION_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SUBJECT_ID     NUMBER NOT NULL CONSTRAINT FK_QQ_SUBJECT REFERENCES QUIZ_SUBJECTS(SUBJECT_ID) ON DELETE CASCADE,
    QUESTION_TEXT  VARCHAR2(1000) NOT NULL,
    OPTION_A       VARCHAR2(500) NOT NULL,
    OPTION_B       VARCHAR2(500) NOT NULL,
    OPTION_C       VARCHAR2(500) NOT NULL,
    OPTION_D       VARCHAR2(500) NOT NULL,
    CORRECT_ANSWER VARCHAR2(500) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_QUESTION_TEXT UNIQUE (SUBJECT_ID, QUESTION_TEXT)
);

-- 3. QUIZ_USERS
CREATE TABLE QUIZ_USERS (
    USER_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USERNAME   VARCHAR2(100) NOT NULL CONSTRAINT UQ_USERNAME UNIQUE,
    FULL_NAME  VARCHAR2(150),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 4. QUIZ_ATTEMPTS
CREATE TABLE QUIZ_ATTEMPTS (
    ATTEMPT_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID             NUMBER CONSTRAINT FK_QA_USER REFERENCES QUIZ_USERS(USER_ID) ON DELETE SET NULL,
    SUBJECT_ID          NUMBER NOT NULL CONSTRAINT FK_QA_SUBJECT REFERENCES QUIZ_SUBJECTS(SUBJECT_ID) ON DELETE CASCADE,
    SCORE               NUMBER NOT NULL,
    TOTAL_QUESTIONS     NUMBER NOT NULL,
    PERCENTAGE          NUMBER(5,2) NOT NULL,
    PERFORMANCE_MESSAGE VARCHAR2(100) NOT NULL,
    ATTEMPT_DATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 5. QUIZ_RESPONSES
CREATE TABLE QUIZ_RESPONSES (
    RESPONSE_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ATTEMPT_ID      NUMBER NOT NULL CONSTRAINT FK_QR_ATTEMPT REFERENCES QUIZ_ATTEMPTS(ATTEMPT_ID) ON DELETE CASCADE,
    QUESTION_ID     NUMBER NOT NULL CONSTRAINT FK_QR_QUESTION REFERENCES QUIZ_QUESTIONS(QUESTION_ID) ON DELETE CASCADE,
    SELECTED_OPTION VARCHAR2(500) NOT NULL,
    CORRECT_OPTION  VARCHAR2(500) NOT NULL,
    IS_CORRECT      NUMBER(1) NOT NULL CONSTRAINT CK_QR_CORRECT CHECK (IS_CORRECT IN (0, 1)),
    ANSWERED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

PROMPT ------------------------------------------------------------------------
PROMPT 3. CREATING DATABASE TRIGGERS
PROMPT ------------------------------------------------------------------------

-- Trigger 1: Validate that the correct answer matches one of the four options
CREATE OR REPLACE TRIGGER TRG_CHECK_QUESTION_OPTIONS
BEFORE INSERT OR UPDATE ON QUIZ_QUESTIONS
FOR EACH ROW
BEGIN
    IF :NEW.CORRECT_ANSWER NOT IN (:NEW.OPTION_A, :NEW.OPTION_B, :NEW.OPTION_C, :NEW.OPTION_D) THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'Validation Error: CORRECT_ANSWER ("' || :NEW.CORRECT_ANSWER || '") must match one of OPTION_A, OPTION_B, OPTION_C, or OPTION_D.'
        );
    END IF;
END;
/

-- Trigger 2: Ensure ATTEMPT_DATE timestamp is always present
CREATE OR REPLACE TRIGGER TRG_ATTEMPT_TIMESTAMP
BEFORE INSERT ON QUIZ_ATTEMPTS
FOR EACH ROW
BEGIN
    IF :NEW.ATTEMPT_DATE IS NULL THEN
        :NEW.ATTEMPT_DATE := CURRENT_TIMESTAMP;
    END IF;
END;
/

